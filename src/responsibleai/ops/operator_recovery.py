"""Offline nonproduction recovery: python -m responsibleai.ops.operator_recovery.

The trust profile path must already be pinned in trusted host configuration.
Private operator signing keys are never loaded or generated by this command.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
from dataclasses import asdict
from pathlib import Path

from responsibleai.data_governance.operator_recovery import RecoveryManifest
from responsibleai.data_governance.operator_recovery_control import (
    OperatorProfile,
    _latest,
    _private_json,
    execute_offline_recovery,
    initialize_control_ledger,
    prepare_offline_recovery,
)


async def _run(arguments) -> dict:
    profile_path = Path(arguments.profile)
    profile = OperatorProfile.load(profile_path)
    if arguments.operation == "initialize-nonproduction-ledger":
        initialize_control_ledger(profile.ledger_path)
        return {"status": "NONPRODUCTION_LEDGER_INITIALIZED"}
    if arguments.operation == "inspect":
        row = _latest(profile)
        return {
            "phase": row["phase"] if row else "NO_RECOVERY_OPERATION",
            "epoch": row["epoch"] if row else 0,
            "request_id": row["request_id"] if row else None,
        }
    from responsibleai.data_governance.backup_defense import (
        RestoreReadinessGate,
        SqliteDurableLifecycleStateProvider,
    )
    from responsibleai.db.engine import create_engine

    if not profile.store_b_path.is_file():
        raise ValueError("Existing durable Store B is required")
    url = os.environ.get("WHITEPACT_OPERATOR_RECOVERY_DATABASE_URL")
    if not url:
        raise ValueError("Operator database connection is not configured")
    provider = SqliteDurableLifecycleStateProvider(profile.store_b_path)
    engine = create_engine(url)
    try:
        if arguments.operation == "prepare":
            manifest = await prepare_offline_recovery(engine, provider, profile_path=profile_path)
            output = json.dumps(
                {"manifest": asdict(manifest), "signatures": {}}, sort_keys=True
            ).encode()
            descriptor = os.open(
                arguments.output, os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o600
            )
            try:
                with os.fdopen(descriptor, "wb") as stream:
                    stream.write(output)
                    stream.flush()
                    os.fsync(stream.fileno())
            except BaseException:
                # Leave any incomplete file for explicit operator inspection;
                # never delete/overwrite a previous signed request implicitly.
                raise
            return {"status": "PREPARED_NOT_AUTHORIZED", "request_id": manifest.request_id}
        request = _private_json(Path(arguments.request))
        if set(request) != {"manifest", "signatures"}:
            raise ValueError("Exact signed request envelope required")
        report = await execute_offline_recovery(
            engine,
            provider,
            RestoreReadinessGate(provider=provider, db_engine=engine),
            profile_path=profile_path,
            manifest=RecoveryManifest(**request["manifest"]),
            signatures=request["signatures"],
        )
        return {"status": report.status, "reconciliation_id": report.id}
    finally:
        await engine.close()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", required=True)
    commands = parser.add_subparsers(dest="operation", required=True)
    commands.add_parser("initialize-nonproduction-ledger")
    commands.add_parser("inspect")
    prepare = commands.add_parser("prepare")
    prepare.add_argument("--output", required=True)
    execute = commands.add_parser("execute")
    execute.add_argument("--request", required=True)
    arguments = parser.parse_args()
    try:
        result = asyncio.run(_run(arguments))
    except Exception:
        # No credentials, SQL parameters, stack traces or backend diagnostics on
        # the operator console. Detailed evidence remains in protected stores.
        print(json.dumps({"status": "RECOVERY_REJECTED_OR_FAILED"}))
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
