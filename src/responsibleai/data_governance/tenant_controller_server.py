"""Internal UDS-only controller service. No customer/public recovery endpoint.

Production enrollment and activation are forbidden. Configuration and disposable
keys are supplied offline, never generated by a web application or this server.
"""

import argparse
import base64
import json
import os
import socket
import stat
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

from responsibleai.data_governance.backup_defense import SqliteDurableLifecycleStateProvider
from responsibleai.data_governance.provisioning_manifest import (
    ProvisionerTrust,
    ProvisioningAuthorizationError,
)
from responsibleai.data_governance.tenant_controller import ProtectedTenantController
from responsibleai.db.engine import create_engine
from responsibleai.environment import is_production


def controller_app(controller: ProtectedTenantController) -> FastAPI:
    application = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)

    @application.post("/internal/provision")
    async def provision(request: Request):
        body = bytearray()
        async for chunk in request.stream():
            body.extend(chunk)
            if len(body) > 16384:
                return JSONResponse({"code": "INVALID_CREATION_REQUEST"}, status_code=400)
        try:
            values = json.loads(body)
            expected = {
                "session_token",
                "csrf",
                "request_id",
                "name",
                "slug",
                "kind",
                "attach_session",
                "monthly_budget_usd",
            }
            if (
                type(values) is not dict
                or set(values) != expected
                or any(
                    type(values[name]) is not str or len(values[name]) > 4096
                    for name in expected - {"attach_session", "monthly_budget_usd"}
                )
                or type(values["attach_session"]) is not bool
            ):
                raise ValueError("Invalid fields")
            tenant = await controller.create(**values)
            return {"tenant_id": tenant, "state": "COMPLETE"}
        except ProvisioningAuthorizationError:
            return JSONResponse({"code": "CREATION_NOT_AUTHORIZED"}, status_code=403)
        except (ValueError, TypeError, json.JSONDecodeError):
            return JSONResponse({"code": "INVALID_CREATION_REQUEST"}, status_code=400)
        except Exception:
            # Never return/log SQL parameters, credentials or a false success.
            return JSONResponse({"code": "CREATION_UNCONFIRMED"}, status_code=503)

    return application


def main() -> None:
    import uvicorn

    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, required=True)
    options = parser.parse_args()
    if is_production():
        raise RuntimeError("Production controller activation is not authorized")
    descriptor = os.open(options.config, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(descriptor) as stream:
        info = os.fstat(stream.fileno())
        if (
            not stat.S_ISREG(info.st_mode)
            or info.st_uid != os.getuid()
            or stat.S_IMODE(info.st_mode) != 0o600
        ):
            raise RuntimeError("Protected controller configuration required")
        config = json.load(stream)
    if config["purpose"] != "NONPRODUCTION_PROVISIONING_QUALIFICATION":
        raise RuntimeError("Unqualified controller configuration")
    socket_path = Path(config["socket_path"])
    parent = socket_path.parent.stat()
    if (
        not socket_path.is_absolute()
        or socket_path.exists()
        or parent.st_uid != os.getuid()
        or stat.S_IMODE(parent.st_mode) & 0o022
    ):
        raise RuntimeError("Private, unused controller socket path required")
    provider = SqliteDurableLifecycleStateProvider(
        config["store_b_path"], secret_key=config["store_b_key"]
    )
    trust = ProvisionerTrust(
        **(config["trust"] | {"public_key": bytes.fromhex(config["trust"]["public_key"])})
    )
    private = Ed25519PrivateKey.from_private_bytes(
        base64.b64decode(config["private_key"], validate=True)
    )
    controller = ProtectedTenantController(
        create_engine(config["database_url"]), provider, trust, private
    )
    # Uvicorn's uds= path explicitly chmods a newly created socket to 0666.
    # Bind privately ourselves and hand over the descriptor, never a TCP port.
    os.umask(0o077)
    listener = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    try:
        listener.bind(str(socket_path))
        os.chmod(socket_path, 0o660)
        listener.listen(128)
        server = uvicorn.Server(
            uvicorn.Config(controller_app(controller), access_log=False, log_level="critical")
        )
        server.run(sockets=[listener])
    finally:
        listener.close()


if __name__ == "__main__":
    main()
